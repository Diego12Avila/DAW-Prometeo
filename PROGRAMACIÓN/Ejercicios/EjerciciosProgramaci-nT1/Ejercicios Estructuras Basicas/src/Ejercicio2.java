/*
Crea un programa que defina una variable
llamada puntuación con valor inicial 0. Luego,
modifica su valor tres veces y muestra el resultado final.

Ejemplo de salida por consola:

Puntuación inicial: 0
Después de primera modificación: 5
Después de segunda modificación: 10
Puntuación final: 15
*/

public class Ejercicio2 {

    public static void main(String[] args) {
        int number = 0;
        System.out.println("Puntuacion inicual: "+number);
        number = 10;
        System.out.println("Despues de la primera modificación: "+number);
        number = 20;
        System.out.println("Despues de la segunda modificación: "+number);
        number = 30;
        System.out.println("Puntuacion final: " +number);
    }
}
